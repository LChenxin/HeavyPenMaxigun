local previous_update = update
local self_update
local api, game

self_update = function(dt, ...)
    state.updates = state.updates + 1

    if state.phase == 'waiting_for_update' then
        state.phase = 'verifying_build'
        local ok, result, module = pcall(begin, state)
        if not ok then
            state.phase = 'failed: ' .. tostring(result)
            report(state.phase)
            pcall(write_report, state)
        elseif not result then
            state.phase = 'unsupported_build'
            report(state.phase)
            pcall(write_report, state)
        else
            api, game = result, module
            state.results = {}
            state.phase = 'scanning_globals'
            report('build verified; scanning ' .. GLOBALS.size .. ' bytes of globals')
        end
    elseif state.phase == 'scanning_globals' then
        local ok, done = pcall(scan_chunks, api, game, state)
        if not ok then
            state.phase = 'failed: ' .. tostring(done)
            report(state.phase)
            pcall(write_report, state)
        elseif done then
            state.phase = 'probing_candidates'
            report(string.format('scan complete: %d candidate pointers from %d bytes (%d unreadable chunks)',
                                 state.candidates, state.scanned, state.chunk_failures))
        end
    elseif state.phase == 'probing_candidates' then
        local ok, done = pcall(probe_candidates, api, state)
        if not ok then
            state.phase = 'failed: ' .. tostring(done)
            report(state.phase)
            pcall(write_report, state)
        elseif done then
            state.phase = 'complete'
            report(string.format('found %d DL settings buffers from %d probes', state.hits, state.probed))
            if pcall(write_report, state) then
                report('wrote HpmgDlProbe.log')
            end
        end
    end

    -- Finished or failed: stop costing frames, but only release the callback
    -- while we still own it. A later mod may have wrapped us since load.
    if state.phase == 'complete' or state.phase:find('^failed') or state.phase == 'unsupported_build' then
        if update == self_update then update = previous_update or function() end end
    end

    if previous_update then return previous_update(dt, ...) end
end
update = self_update

report('loaded; waiting for the first update tick')
