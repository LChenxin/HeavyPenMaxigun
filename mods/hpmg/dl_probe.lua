-- HD2-Addon: mods/hpmg/dl_probe
--
-- L2 read-only probe: find every datalibrary (DL) settings buffer the game has
-- loaded, and the game.dll global that points at each one.
--
-- WHY THIS WORKS
--   game.dll is Themida/WinLicense packed (.winlice section, entry in .boot,
--   section entropy 8.0), so nothing can be read statically from the file. The
--   .dl_bin files on disk are encrypted too. But once the game decrypts a
--   settings blob into the heap it is plain datalibrary layout:
--
--     base +0   u32  instance count
--          +4   u32  0x444C444C  'LDLD'      <- per-instance header starts here
--          +8   u32  version (1)
--          +12  u32  root type id
--          +16  u32  payload size
--          +20  u32  is_64_bit_ptr (1)
--          +24  u32  reserved (0)
--          +28  root: [ptr to items][u32 item count]
--          ... next instance header follows the payload ...
--
--   BetterStratagemBounce reaches exactly one of these via game.dll+0x2791F68
--   and validates 11 instances of type 0x30EB6399 totalling 79296 bytes. That
--   is our ground truth: if this probe does not rediscover that buffer at that
--   RVA with that size, the probe is wrong and every other result is suspect.
--
--   Buffers are named by size. generated_stratagem_settings.dl_bin is 79344
--   bytes on disk and 79296 in memory, a constant 48 bytes of crypto framing,
--   so decrypted_size == file_size - 48 for each shipped settings file.
--
-- This module only ever reads. It never writes process memory.

if rawget(_G, 'HpmgDlProbe') then return end

