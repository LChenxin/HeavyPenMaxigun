local scan_state = {offset = 0, seen = {}, queue = {}, queue_at = 1}

local function begin(state)
    local api = create_api()
    local exe, game = api.module(nil), api.module('game.dll')
    assert(exe and game, 'Required game modules unavailable')
    local exe_hash, game_hash = api.module_hash(exe), api.module_hash(game)
    if exe_hash ~= BUILD.exe_sha256 or game_hash ~= BUILD.game_sha256 then
        state.build_note = 'Unsupported build; RVAs below mean nothing. exe='
            .. exe_hash:sub(1, 16) .. ' game=' .. game_hash:sub(1, 16)
        return nil
    end
    state.build_note = 'Build matches the supported Steam 24826606 / 1.8.45317.0 image.'
    return api, game
end

-- Collect pointer-shaped qwords out of the globals section, a few chunks per tick.
local function scan_chunks(api, game, state)
    for _ = 1, CHUNKS_PER_TICK do
        if scan_state.offset >= GLOBALS.size then return true end
        local size = math.min(CHUNK, GLOBALS.size - scan_state.offset)
        size = size - (size % 8)
        if size <= 0 then return true end
        local base = GLOBALS.rva + scan_state.offset
        if api.read_chunk(game + base, size) then
            for index = 0, size / 8 - 1 do
                local value = api.word(index)
                -- Heap allocations are at least 8-byte aligned; the upper bound
                -- is the Windows x64 user-mode limit.
                if value >= 0x10000ULL and value < 0x800000000000ULL
                    and (value % 8ULL) == 0 then
                    local address = tonumber(value)
                    if not scan_state.seen[address] then
                        scan_state.seen[address] = base + index * 8
                        scan_state.queue[#scan_state.queue + 1] = address
                        state.candidates = state.candidates + 1
                    end
                end
            end
        else
            state.chunk_failures = state.chunk_failures + 1
        end
        scan_state.offset = scan_state.offset + size
        state.scanned = scan_state.offset
    end
    return false
end

-- Test queued candidates against the DL header signature, a batch per tick.
local function probe_candidates(api, state)
    local processed = 0
    while scan_state.queue_at <= #scan_state.queue and processed < PROBES_PER_TICK do
        local address = scan_state.queue[scan_state.queue_at]
        scan_state.queue_at = scan_state.queue_at + 1
        processed = processed + 1
        state.probed = state.probed + 1
        local total, type_id, instances, mixed = measure(api, ffi.cast('uint8_t *', address))
        if total then
            state.hits = state.hits + 1
            state.results[#state.results + 1] = {
                rva = scan_state.seen[address],
                address = address,
                total = total,
                type_id = type_id,
                text = describe(total, type_id, instances, mixed),
            }
        end
    end
    return scan_state.queue_at > #scan_state.queue
end

