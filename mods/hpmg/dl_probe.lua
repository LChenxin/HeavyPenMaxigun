-- Struct tags are global to the LuaJIT VM and other CowboyBingus mods declare
-- their own copy of MEMORY_BASIC_INFORMATION, so this name must stay unique.
-- Duplicate *function* declarations with identical signatures are harmless.
local function create_api()
    assert(ffi.abi('64bit'), 'Windows x64 is required')
    ffi.cdef [[
        void *GetModuleHandleA(const char *name);
        uint32_t GetModuleFileNameW(void *module, uint16_t *path, uint32_t capacity);
        void *GetCurrentProcess(void);
        int ReadProcessMemory(void *process, const void *address, void *buffer, size_t size, size_t *read);
        void *CreateFileW(const uint16_t *path, uint32_t access, uint32_t share, void *security,
                          uint32_t disposition, uint32_t flags, void *template_file);
        int ReadFile(void *file, void *buffer, uint32_t size, uint32_t *read, void *overlapped);
        int CloseHandle(void *handle);
        int32_t BCryptOpenAlgorithmProvider(void **algorithm, const uint16_t *name,
                                            const uint16_t *provider, uint32_t flags);
        int32_t BCryptCloseAlgorithmProvider(void *algorithm, uint32_t flags);
        int32_t BCryptCreateHash(void *algorithm, void **hash, void *object, uint32_t object_size,
                                 const void *secret, uint32_t secret_size, uint32_t flags);
        int32_t BCryptHashData(void *hash, const void *data, uint32_t size, uint32_t flags);
        int32_t BCryptFinishHash(void *hash, void *digest, uint32_t size, uint32_t flags);
        int32_t BCryptDestroyHash(void *hash);
    ]]
    local kernel, bcrypt = ffi.load('kernel32'), ffi.load('bcrypt')
    local process = kernel.GetCurrentProcess()
    local api = {}

    local scan = ffi.new('uint8_t[?]', CHUNK)
    local scan_words = ffi.cast('uint64_t *', scan)
    local small = ffi.new('uint8_t[64]')
    local small_words = ffi.cast('uint32_t *', small)
    local count = ffi.new('size_t[1]')

    function api.module(name)
        local handle = kernel.GetModuleHandleA(name)
        if handle == nil then return nil end
        return ffi.cast('uint8_t *', handle)
    end

    -- Bulk read into the scan buffer; the caller reads it through scan_words.
    function api.read_chunk(address, size)
        if kernel.ReadProcessMemory(process, address, scan, size, count) == 0 then return false end
        return count[0] == size
    end

    function api.word(index) return scan_words[index] end

    -- Small read into the header buffer, exposed as u32 lanes.
    function api.read_header(address, size)
        if kernel.ReadProcessMemory(process, address, small, size, count) == 0 then return false end
        return count[0] == size
    end

    function api.header(index) return small_words[index] end

    function api.module_hash(module)
        local path = ffi.new('uint16_t[32768]')
        local length = kernel.GetModuleFileNameW(module, path, 32768)
        assert(length > 0 and length < 32768, 'Cannot resolve module file')
        local file = kernel.CreateFileW(path, 0x80000000, 7, nil, 3, 0x08000000, nil)
        assert(file ~= ffi.cast('void *', -1), 'Cannot read module file')
        local algorithm, hash = ffi.new('void *[1]'), ffi.new('void *[1]')
        local ok, result = pcall(function()
            local name = ffi.new('uint16_t[7]', {83, 72, 65, 50, 53, 54, 0})
            assert(bcrypt.BCryptOpenAlgorithmProvider(algorithm, name, nil, 0) == 0, 'SHA256 unavailable')
            assert(bcrypt.BCryptCreateHash(algorithm[0], hash, nil, 0, nil, 0, 0) == 0, 'SHA256 creation failed')
            local buffer, read = ffi.new('uint8_t[1048576]'), ffi.new('uint32_t[1]')
            while true do
                assert(kernel.ReadFile(file, buffer, 1048576, read, nil) ~= 0, 'Module file read failed')
                if read[0] == 0 then break end
                assert(bcrypt.BCryptHashData(hash[0], buffer, read[0], 0) == 0, 'SHA256 update failed')
            end
            local digest, hex = ffi.new('uint8_t[32]'), {}
            assert(bcrypt.BCryptFinishHash(hash[0], digest, 32, 0) == 0, 'SHA256 finish failed')
            for i = 0, 31 do hex[#hex + 1] = string.format('%02X', digest[i]) end
            return table.concat(hex)
        end)
        if hash[0] ~= nil then bcrypt.BCryptDestroyHash(hash[0]) end
        if algorithm[0] ~= nil then bcrypt.BCryptCloseAlgorithmProvider(algorithm[0], 0) end
        kernel.CloseHandle(file)
        if not ok then error(result) end
        return result
    end

    return api
end

-- Walk the instance chain at `address` and return its total byte size, the root
-- type id, and the instance count -- or nil with a reason.
local function measure(api, address)
    if not api.read_header(address, 28) then return nil, 'unreadable' end
    local instances = api.header(0)
    if instances < 1 or instances > MAX_INSTANCES then return nil, 'count' end
    if api.header(1) ~= DL_MAGIC then return nil, 'magic' end
    if api.header(2) ~= 1 then return nil, 'version' end
    if api.header(5) ~= 1 then return nil, 'not 64-bit' end
    if api.header(6) ~= 0 then return nil, 'reserved' end

    local type_id = api.header(3)
    local offset = 4
    local mixed = false
    for _ = 1, instances do
        if not api.read_header(address + offset, 24) then return nil, 'chain unreadable' end
        if api.header(0) ~= DL_MAGIC then return nil, 'chain magic' end
        if api.header(1) ~= 1 then return nil, 'chain version' end
        if api.header(2) ~= type_id then mixed = true end
        if api.header(4) ~= 1 then return nil, 'chain not 64-bit' end
        local payload = api.header(3)
        offset = offset + 24 + payload
        if offset > MAX_TOTAL then return nil, 'oversize' end
    end
    return offset, type_id, instances, mixed
end

local function describe(total, type_id, instances, mixed)
    local label = FINGERPRINTS[total]
    local note
    if label then
        note = label
    else
        note = 'UNMATCHED (no shipped .dl_bin is ' .. tostring(total + 48) .. ' bytes)'
    end
    if mixed then note = note .. ' [mixed type ids]' end
    return string.format('type 0x%08X  instances %3d  total %9d  = %s',
                         type_id, instances, total, note)
end

-- Exposed so tests/test_dl_probe.lua can drive the parser against synthetic
-- buffers, the way the sample mods test their layouts without attaching to the
-- game. Carrying these references costs nothing at runtime.
state.internals = {measure = measure, describe = describe, fingerprints = FINGERPRINTS,
                   ground_truth = GROUND_TRUTH, globals = GLOBALS}

local function write_report(state)
    local loader = rawget(_G, 'CowboyBingusModLoader')
    local file = loader and loader.open_log and loader.open_log('HpmgDlProbe.log')
    if not file then return false end
    file:write(BUILD.revision .. '\n')
    file:write(string.format('phase=%s updates=%d scanned=%d candidates=%d probed=%d hits=%d chunk_failures=%d\n',
                             state.phase, state.updates, state.scanned, state.candidates,
                             state.probed, state.hits, state.chunk_failures))
    if state.build_note then file:write(state.build_note .. '\n') end
    file:write('\nDL settings buffers reachable from game.dll globals:\n')
    local rows = state.results or {}
    table.sort(rows, function(a, b) return a.rva < b.rva end)
    for _, row in ipairs(rows) do
        file:write(string.format('  game.dll+0x%08X -> 0x%012X  %s\n',
                                 row.rva, row.address, row.text))
    end
    file:write('\nGround truth check:\n')
    for rva, expected in pairs(GROUND_TRUTH) do
        local found
        for _, row in ipairs(rows) do
            if row.rva == rva then found = row end
        end
        if not found then
            file:write(string.format('  FAIL game.dll+0x%08X not rediscovered (%s says %s, %d bytes)\n',
                                     rva, expected.source, expected.name, expected.total))
        elseif found.total == expected.total and found.type_id == expected.type_id then
            file:write(string.format('  PASS game.dll+0x%08X  %s  type 0x%08X  %d bytes, agrees with %s\n',
                                     rva, expected.name, expected.type_id, expected.total, expected.source))
        else
            file:write(string.format('  FAIL game.dll+0x%08X  got type 0x%08X %d bytes, expected type 0x%08X %d bytes\n',
                                     rva, found.type_id, found.total, expected.type_id, expected.total))
        end
    end
    file:close()
    return true
end

