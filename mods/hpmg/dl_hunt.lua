local function create_api()
    assert(ffi.abi('64bit'), 'Windows x64 is required')
    ffi.cdef [[
        void *GetModuleHandleA(const char *name);
        uint32_t GetModuleFileNameW(void *module, uint16_t *path, uint32_t capacity);
        void *GetCurrentProcess(void);
        int ReadProcessMemory(void *process, const void *address, void *buffer, size_t size, size_t *read);
        void *CreateFileW(const uint16_t *path, uint32_t access, uint32_t share, void *security,
                          uint32_t disposition, uint32_t flags, void *template_file);
        int ReadFile(void *file, void *buffer, uint32_t size, uint32_t *read, void *overlapped);
        int CloseHandle(void *handle);
        int32_t BCryptOpenAlgorithmProvider(void **algorithm, const uint16_t *name,
                                            const uint16_t *provider, uint32_t flags);
        int32_t BCryptCloseAlgorithmProvider(void *algorithm, uint32_t flags);
        int32_t BCryptCreateHash(void *algorithm, void **hash, void *object, uint32_t object_size,
                                 const void *secret, uint32_t secret_size, uint32_t flags);
        int32_t BCryptHashData(void *hash, const void *data, uint32_t size, uint32_t flags);
        int32_t BCryptFinishHash(void *hash, void *digest, uint32_t size, uint32_t flags);
        int32_t BCryptDestroyHash(void *hash);
        typedef struct {
            void *base; void *allocation_base; uint32_t allocation_protection;
            uint16_t partition; uint16_t reserved; size_t size;
            uint32_t state; uint32_t protection; uint32_t type;
        } HpmgMemoryRegion;
        size_t VirtualQuery(const void *address, void *region, size_t size);
    ]]
    local kernel, bcrypt = ffi.load('kernel32'), ffi.load('bcrypt')
    local process = kernel.GetCurrentProcess()
    local api = {}

    local scan = ffi.new('uint8_t[?]', CHUNK)
    local scan_words = ffi.cast('uint64_t *', scan)
    local small = ffi.new('uint8_t[64]')
    local small_words = ffi.cast('uint32_t *', small)
    local count = ffi.new('size_t[1]')
    local big                      -- allocated on first dump; 48 MB is not cheap

    function api.module(name)
        local handle = kernel.GetModuleHandleA(name)
        if handle == nil then return nil end
        return ffi.cast('uint8_t *', handle)
    end

    function api.read_chunk(address, size)
        if kernel.ReadProcessMemory(process, address, scan, size, count) == 0 then return false end
        return count[0] == size
    end

    function api.word(index) return scan_words[index] end

    -- Handed out whole rather than read through an accessor: the sweep compares
    -- half a million lanes per tick, and a function call per lane is the
    -- difference between a few milliseconds and a visible hitch.
    local scan_words32 = ffi.cast('uint32_t *', scan)
    function api.scan32() return scan_words32 end

    function api.read_header(address, size)
        if size > 64 then return false end
        if kernel.ReadProcessMemory(process, address, small, size, count) == 0 then return false end
        return count[0] == size
    end

    function api.header(index) return small_words[index] end

    function api.capture(address, size, sink)
        if size < 1 or size > MAX_DUMP then return false, 'size out of range' end
        if not big then big = ffi.new('uint8_t[?]', MAX_DUMP) end
        if kernel.ReadProcessMemory(process, address, big, size, count) == 0 then
            return false, 'read failed'
        end
        if count[0] ~= size then return false, 'short read' end
        -- Write in slices: one 45 MB Lua string would be a large, pointless copy.
        local offset = 0
        while offset < size do
            local slice = math.min(1048576, size - offset)
            sink(ffi.string(big + offset, slice))
            offset = offset + slice
        end
        return true
    end

    -- Committed private read/write regions, largest first. A 45 MB settings
    -- blob cannot hide in a small region, so size ordering finds the big
    -- targets long before the scan has to grind through the small ones.
    function api.regions(minimum)
        local region = ffi.new('HpmgMemoryRegion[1]')
        local size = ffi.sizeof(region[0])
        local found = {}
        local cursor = ffi.cast('uint8_t *', 0x10000ULL)
        local limit = ffi.cast('uint8_t *', 0x7FFFFFFF0000ULL)
        local guard = 0
        while cursor < limit do
            guard = guard + 1
            if guard > 200000 then break end
            if kernel.VirtualQuery(cursor, region, size) ~= size then break end
            local length = tonumber(region[0].size)
            if length <= 0 then break end
            -- MEM_COMMIT, MEM_PRIVATE, and writable or read-only data pages.
            if region[0].state == 0x1000 and region[0].type == 0x20000
                and (region[0].protection == 4 or region[0].protection == 2)
                and length >= minimum then
                -- Cast away void *: LuaJIT will not do arithmetic on it, and
                -- the sweep advances through this base byte by byte.
                found[#found + 1] = {base = ffi.cast('uint8_t *', region[0].base), size = length}
            end
            cursor = cursor + length
        end
        table.sort(found, function(a, b) return a.size > b.size end)
        return found
    end

    function api.module_hash(module)
        local path = ffi.new('uint16_t[32768]')
        local length = kernel.GetModuleFileNameW(module, path, 32768)
        assert(length > 0 and length < 32768, 'Cannot resolve module file')
        local file = kernel.CreateFileW(path, 0x80000000, 7, nil, 3, 0x08000000, nil)
        assert(file ~= ffi.cast('void *', -1), 'Cannot read module file')
        local algorithm, hash = ffi.new('void *[1]'), ffi.new('void *[1]')
        local ok, result = pcall(function()
            local name = ffi.new('uint16_t[7]', {83, 72, 65, 50, 53, 54, 0})
            assert(bcrypt.BCryptOpenAlgorithmProvider(algorithm, name, nil, 0) == 0, 'SHA256 unavailable')
            assert(bcrypt.BCryptCreateHash(algorithm[0], hash, nil, 0, nil, 0, 0) == 0, 'SHA256 creation failed')
            local buffer, read = ffi.new('uint8_t[1048576]'), ffi.new('uint32_t[1]')
            while true do
                assert(kernel.ReadFile(file, buffer, 1048576, read, nil) ~= 0, 'Module file read failed')
                if read[0] == 0 then break end
                assert(bcrypt.BCryptHashData(hash[0], buffer, read[0], 0) == 0, 'SHA256 update failed')
            end
            local digest, hex = ffi.new('uint8_t[32]'), {}
            assert(bcrypt.BCryptFinishHash(hash[0], digest, 32, 0) == 0, 'SHA256 finish failed')
            for i = 0, 31 do hex[#hex + 1] = string.format('%02X', digest[i]) end
            return table.concat(hex)
        end)
        if hash[0] ~= nil then bcrypt.BCryptDestroyHash(hash[0]) end
        if algorithm[0] ~= nil then bcrypt.BCryptCloseAlgorithmProvider(algorithm[0], 0) end
        kernel.CloseHandle(file)
        if not ok then error(result) end
        return result
    end

    return api
end

-- Returns total, type_id, instances, mixed  -- or nil, reason, had_header.
-- had_header says the candidate really did carry an 'LDLD' header, which is
-- what separates a near miss worth reporting from ordinary random memory.
local function measure(api, address)
    if not api.read_header(address, 28) then return nil, 'unreadable', false end
    if api.header(1) ~= DL_MAGIC then return nil, 'no magic', false end
    local had = true
    if api.header(2) ~= 1 then return nil, 'version ' .. api.header(2), had end
    local instances = api.header(0)
    if instances < 1 then return nil, 'zero instances', had end
    if instances > MAX_INSTANCES then
        return nil, 'instance cap: ' .. instances, had
    end
    if api.header(5) ~= 1 then return nil, 'not 64-bit', had end
    if api.header(6) ~= 0 then return nil, 'reserved set', had end

    local type_id = api.header(3)
    local offset, mixed = 4, false
    for index = 1, instances do
        if not api.read_header(address + offset, 24) then
            return nil, string.format('chain unreadable at instance %d/%d', index, instances), had
        end
        if api.header(0) ~= DL_MAGIC then
            return nil, string.format('chain magic at instance %d/%d', index, instances), had
        end
        if api.header(1) ~= 1 then return nil, 'chain version', had end
        if api.header(2) ~= type_id then mixed = true end
        offset = offset + 24 + api.header(3)
        if offset > MAX_TOTAL then return nil, 'total cap', had end
    end
    return offset, type_id, instances, mixed
end

local function note_reject(state, reason)
    state.near_misses = state.near_misses + 1
    state.rejects[reason] = (state.rejects[reason] or 0) + 1
end

local function log_directory(loader)
    if loader and loader.log_directory then return loader.log_directory end
    if loader and loader.open_log then
        local probe = loader.open_log('HpmgDlHunt.log')
        if probe then probe:close() end
        return loader.log_directory
    end
end

local function write_dump(api, state, name, address, total, type_id, instances)
    local loader = rawget(_G, 'CowboyBingusModLoader')
    local directory = log_directory(loader)
    if not directory then return false, 'no log directory' end
    local path = directory .. '/HpmgDump_' .. name .. '.bin'
    local file, reason = io.open(path, 'wb')
    if not file then return false, tostring(reason) end

    local header = ffi.new('uint8_t[32]')
    ffi.copy(header, 'HPMGDUMP', 8)
    local words = ffi.cast('uint32_t *', header + 8)
    words[0] = 1
    words[1] = type_id
    ffi.cast('uint64_t *', header + 16)[0] = ffi.cast('uintptr_t', address)
    words = ffi.cast('uint32_t *', header + 24)
    words[0] = total
    words[1] = instances
    file:write(ffi.string(header, 32))

    local ok, problem = api.capture(address, total, function(slice) file:write(slice) end)
    file:close()
    if not ok then return false, problem end
    return true, path
end

-- One place decides what a discovered buffer is called, whether it is new, and
-- whether it gets written to disk -- so the pointer scan and the memory sweep
-- cannot drift into reporting the same buffer two different ways.
local function record_buffer(api, state, key, address, total, type_id, instances, mixed, origin)
    if state.found[key] then return false end
    state.hits = state.hits + 1
    local name = FINGERPRINTS[total] or ('UNMATCHED_' .. total)
    state.found[key] = string.format('type 0x%08X  instances %6d  total %9d  = %s%s  (%s)',
                                     type_id, instances, total, name,
                                     mixed and ' [mixed type ids]' or '', origin)
    report(key .. ' -> ' .. state.found[key])
    if DUMP_THESE[name] and not state.files[name] then
        local ok, detail = write_dump(api, state, name, address, total, type_id, instances)
        state.files[name] = ok and detail or ('FAILED: ' .. tostring(detail))
        if ok then state.dumped = state.dumped + 1 end
        report(name .. ' dump: ' .. tostring(state.files[name]))
    end
    return true
end

