local previous_update = update
local self_update
local api, game
local idle = 0

self_update = function(dt, ...)
    state.updates = state.updates + 1

    if state.phase == 'waiting_for_update' then
        local ok, result, module = pcall(function()
            local created = create_api()
            local exe, dll = created.module(nil), created.module('game.dll')
            assert(exe and dll, 'Required game modules unavailable')
            assert(created.module_hash(exe) == BUILD.exe_sha256, 'Unsupported executable')
            assert(created.module_hash(dll) == BUILD.game_sha256, 'Unsupported game module')
            return created, dll
        end)
        if not ok then
            state.phase = 'failed: ' .. tostring(result)
            report(state.phase)
            pcall(write_report, state)
        else
            api, game = result, module
            state.build_note = 'Build matches Steam 24826606 / 1.8.45317.0.'
            state.phase = 'scanning'
            report('build verified; hunting, rescan every ' .. RESCAN_TICKS .. ' ticks')
        end

    elseif state.phase == 'scanning' then
        local ok, done = pcall(scan_chunks, api, game, state)
        if not ok then
            state.phase = 'failed: ' .. tostring(done)
            report(state.phase)
        elseif done then
            state.phase = 'probing'
        end

    elseif state.phase == 'probing' then
        local ok, done = pcall(probe_candidates, api, state)
        if not ok then
            state.phase = 'failed: ' .. tostring(done)
            report(state.phase)
        elseif done then
            local ready, problem = pcall(reset_sweep, api)
            if not ready then
                state.phase = 'failed: regions: ' .. tostring(problem)
                report(state.phase)
            else
                state.sweep_regions = #sweep_state.regions
                state.phase = 'sweeping'
                report(string.format('globals done (%d buffers); sweeping %d regions >= %d MB',
                                     state.hits, state.sweep_regions,
                                     math.floor(SWEEP_MIN_REGION / 1048576)))
            end
        end

    elseif state.phase == 'sweeping' then
        local ok, done = pcall(sweep_memory, api, state)
        if not ok then
            state.phase = 'failed: ' .. tostring(done)
            report(state.phase)
        else
            state.sweep_bytes = sweep_state.bytes
            if done then
                state.cycles = state.cycles + 1
                state.phase = 'idle'
                idle = 0
                pcall(write_report, state)
                report(string.format('cycle %d done: %d buffers (%d from sweep), %d near misses, %d dumps',
                                     state.cycles, state.hits, state.sweep_hits,
                                     state.near_misses, state.dumped))
            end
        end

    elseif state.phase == 'idle' then
        -- Settings load lazily, so look again later in the session.
        idle = idle + 1
        if idle >= RESCAN_TICKS then
            reset_scan()
            state.phase = 'scanning'
        end
    end

    if state.phase:find('^failed') then
        if update == self_update then update = previous_update or function() end end
    end

    if previous_update then return previous_update(dt, ...) end
end
update = self_update

report('loaded; waiting for the first update tick')
