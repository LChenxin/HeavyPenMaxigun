-- HD2-Addon: mods/hpmg/dl_hunt
--
-- L2.6: dl_probe and dl_dump merged, with the two things they got wrong fixed.
--
-- WHAT WENT WRONG BEFORE
--   dl_probe capped a buffer at 512 instances and 64 MB, then silently dropped
--   anything larger. generated_entities.dl_bin is 45.6 MB and is where weapon
--   definitions almost certainly live, so the one buffer that mattered most may
--   have been rejected without leaving a trace. A scanner that only reports
--   successes cannot tell you why it failed. This one reports near misses:
--   anything carrying a valid 'LDLD' header that was then thrown away, and the
--   reason it was thrown away.
--
--   dl_probe also scanned once, at whatever moment the first update tick ran.
--   Settings buffers load lazily, so a main-menu scan never sees mission data.
--   This rescans on an interval and dumps buffers as they appear, which lets a
--   single session cover the menu and then a mission.
--
-- Reads process memory only. Writes nothing back.

if rawget(_G, 'HpmgDlHunt') then return end

