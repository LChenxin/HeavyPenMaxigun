local scan_state
local function reset_scan()
    scan_state = {offset = 0, seen = {}, queue = {}, queue_at = 1}
end
reset_scan()

local function scan_chunks(api, game, state)
    for _ = 1, CHUNKS_PER_TICK do
        if scan_state.offset >= GLOBALS.size then return true end
        local size = math.min(CHUNK, GLOBALS.size - scan_state.offset)
        size = size - (size % 8)
        if size <= 0 then return true end
        local base = GLOBALS.rva + scan_state.offset
        if api.read_chunk(game + base, size) then
            for index = 0, size / 8 - 1 do
                local value = api.word(index)
                if value >= 0x10000ULL and value < 0x800000000000ULL and (value % 8ULL) == 0 then
                    local address = tonumber(value)
                    if not scan_state.seen[address] then
                        scan_state.seen[address] = base + index * 8
                        scan_state.queue[#scan_state.queue + 1] = address
                        state.candidates = state.candidates + 1
                    end
                end
            end
        end
        scan_state.offset = scan_state.offset + size
    end
    return false
end

local function probe_candidates(api, state)
    local processed = 0
    while scan_state.queue_at <= #scan_state.queue and processed < PROBES_PER_TICK do
        local address = scan_state.queue[scan_state.queue_at]
        scan_state.queue_at = scan_state.queue_at + 1
        processed = processed + 1
        state.probed = state.probed + 1

        local total, type_id, instances, mixed = measure(api, ffi.cast('uint8_t *', address))
        if not total then
            -- instances is the had_header flag on the failure path.
            if instances then note_reject(state, tostring(type_id)) end
        else
            record_buffer(api, state,
                          string.format('game.dll+0x%08X', scan_state.seen[address]),
                          ffi.cast('uint8_t *', address), total, type_id, instances, mixed,
                          'globals')
        end
    end
    return scan_state.queue_at > #scan_state.queue
end

-- Following pointers out of the globals array reaches 16 of the 54 shipped
-- settings files and nothing else -- with zero near misses, so nothing is being
-- rejected, those buffers simply are not referenced from there. The sweep drops
-- the pointer assumption entirely and looks for the header signature itself:
--     base +4  'LDLD'
--     base +8  version 1
-- anywhere in committed private memory.
local sweep_state

local function reset_sweep(api)
    sweep_state = {regions = api.regions(SWEEP_MIN_REGION), at = 1, offset = 0, bytes = 0}
end

local function sweep_memory(api, state)
    local budget = SWEEP_BYTES_PER_TICK
    while budget > 0 do
        local region = sweep_state.regions[sweep_state.at]
        if not region then return true end
        if sweep_state.offset >= region.size then
            sweep_state.at = sweep_state.at + 1
            sweep_state.offset = 0
        else
            local size = math.min(CHUNK, region.size - sweep_state.offset)
            size = size - (size % 4)
            if size < 32 then
                sweep_state.at = sweep_state.at + 1
                sweep_state.offset = 0
            else
                local at = region.base + sweep_state.offset
                if api.read_chunk(at, size) then
                    local words = api.scan32()
                    for index = 0, size / 4 - 2 do
                        if words[index] == DL_MAGIC and words[index + 1] == 1 then
                            -- The magic sits 4 bytes into the buffer, after the
                            -- instance count.
                            local base = at + index * 4 - 4
                            if sweep_state.offset + index * 4 >= 4 then
                                local total, type_id, instances, mixed = measure(api, base)
                                if total then
                                    state.sweep_hits = state.sweep_hits + 1
                                    record_buffer(api, state,
                                                  string.format('heap 0x%012X',
                                                                tonumber(ffi.cast('uintptr_t', base))),
                                                  base, total, type_id, instances, mixed, 'sweep')
                                end
                            end
                        end
                    end
                end
                -- Overlap by 8 bytes so a signature never straddles two reads.
                sweep_state.offset = sweep_state.offset + size - 8
                sweep_state.bytes = sweep_state.bytes + size
                budget = budget - size
            end
        end
    end
    return false
end

local function write_report(state)
    local loader = rawget(_G, 'CowboyBingusModLoader')
    local file = loader and loader.open_log and loader.open_log('HpmgDlHunt.log')
    if not file then return false end
    file:write(BUILD.revision .. '\n')
    file:write(string.format('phase=%s updates=%d cycles=%d candidates=%d probed=%d hits=%d near_misses=%d dumped=%d\n',
                             state.phase, state.updates, state.cycles, state.candidates,
                             state.probed, state.hits, state.near_misses, state.dumped))
    file:write(string.format('sweep: regions=%d scanned=%d MB signature_hits=%d\n',
                             state.sweep_regions, math.floor(state.sweep_bytes / 1048576),
                             state.sweep_hits))
    if state.build_note then file:write(state.build_note .. '\n') end

    file:write('\nDL settings buffers found:\n')
    local keys = {}
    for key in pairs(state.found) do keys[#keys + 1] = key end
    table.sort(keys)
    for _, key in ipairs(keys) do
        file:write(string.format('  %-26s %s\n', key, state.found[key]))
    end

    file:write('\nNear misses (had an LDLD header, then failed):\n')
    local reasons = {}
    for reason in pairs(state.rejects) do reasons[#reasons + 1] = reason end
    table.sort(reasons)
    if #reasons == 0 then file:write('  none\n') end
    for _, reason in ipairs(reasons) do
        file:write(string.format('  %6d x  %s\n', state.rejects[reason], reason))
    end

    file:write('\nDumps written:\n')
    local names = {}
    for name in pairs(state.files) do names[#names + 1] = name end
    table.sort(names)
    if #names == 0 then file:write('  none\n') end
    for _, name in ipairs(names) do
        file:write(string.format('  %-32s %s\n', name, state.files[name]))
    end
    file:close()
    return true
end

state.internals = {measure = measure, fingerprints = FINGERPRINTS, dump_these = DUMP_THESE,
